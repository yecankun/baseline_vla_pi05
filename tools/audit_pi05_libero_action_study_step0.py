"""Read-only completed fixed12 step0 audit; never run a model or optimizer.

Default mode additionally replays the three CPU draw manifests under pinned
torch2.10. --metadata-only checks hashes, all trace inputs/targets, reported
statistics and scope without importing torch; it is not a passed draw replay.
Prediction errors and parameter-mutation claims are checked for consistency
with saved sufficient statistics/hashes, not regenerated by a model forward.
"""
